import type { Opportunity, OpportunityCategory, Province } from '@/types';
import { daysFromNow, formatShortDate } from '@/utils/date';

function makeOpportunity(
  input: Omit<Opportunity, 'closes' | 'closingTone' | 'closingDate' | 'lastUpdated'> & {
    closesInDays: number;
    lastUpdatedDaysAgo: number;
  },
): Opportunity {
  const { closesInDays, lastUpdatedDaysAgo, ...rest } = input;
  const closingDate = daysFromNow(closesInDays);
  const closingTone = closesInDays <= 7 ? 'urgent' : closesInDays <= 30 ? 'soon' : 'normal';

  return {
    ...rest,
    closingDate,
    closes: formatShortDate(closingDate),
    closingTone,
    lastUpdated: formatShortDate(daysFromNow(-lastUpdatedDaysAgo)),
    isExpired: closesInDays < 0,
  };
}

